using System;using System.IO;using System.Linq;using UnityEngine;using UnityEditor;using UnityEditor.SceneManagement;using Vaelith.Docencia2;using Object=UnityEngine.Object;
public static class FaseARegression {
 static void Capture(string scene,string prefix){
  EditorSceneManager.OpenScene(scene);var sw=Object.FindAnyObjectByType<Docencia2ModeSwitcher>();
  foreach(var mode in new[]{Docencia2VisualMode.Noche,Docencia2VisualMode.Terror}){
   sw.ApplyMode(mode,false);foreach(var tracker in Object.FindObjectsByType<Docencia2InteriorModeTracker>(FindObjectsInactive.Include))tracker.SendMessage("Update");
   foreach(var camera in GameObject.Find("Camaras_Referencia_Docencia2").GetComponentsInChildren<Camera>(true)){
    var rt=new RenderTexture(1920,1080,24);var oldTarget=camera.targetTexture;var old=RenderTexture.active;var texture=new Texture2D(1920,1080,TextureFormat.RGB24,false);
    camera.targetTexture=rt;for(int i=0;i<3;i++)camera.Render();RenderTexture.active=rt;texture.ReadPixels(new Rect(0,0,1920,1080),0,0);texture.Apply();File.WriteAllBytes(FaseARevision.Output+"/Exterior_"+prefix+"_"+mode+"_"+camera.name+".png",texture.EncodeToPNG());camera.targetTexture=oldTarget;RenderTexture.active=old;Object.DestroyImmediate(texture);rt.Release();Object.DestroyImmediate(rt);
   }
  }
 }
 public static void Run(){
  Directory.CreateDirectory(FaseARevision.Output);string target="Assets/Scenes/FaseA_Temporal_Regresion.unity";
  File.Copy(FaseARevision.Output+"/Antes_Resto.unity",target,true);AssetDatabase.ImportAsset(target);
  Capture(target,"Antes");Capture("Assets/Scenes/Exterior_Docencia2.unity","Despues");
  // This temporary comparison asset is generated by this routine, not a scene audit candidate.
  AssetDatabase.DeleteAsset(target);File.WriteAllText(FaseARevision.Output+"/regresion_ok.txt","6 vistas antes + 6 despues, camaras existentes, 1920x1080. Comparacion contra base de Fase A; no sustituye aprobacion visual del usuario.");
 }
}
